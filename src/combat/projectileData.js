export function interpolatePenetration(ammo, distanceMeters) {
  const table = ammo.penetrationTable;
  if (distanceMeters <= table[0][0]) return table[0][1];
  for (let i = 1; i < table.length; i++) {
    const [d0, p0] = table[i - 1];
    const [d1, p1] = table[i];
    if (distanceMeters <= d1) {
      const t = (distanceMeters - d0) / (d1 - d0);
      return p0 + (p1 - p0) * t;
    }
  }
  return table[table.length - 1][1];
}
